// OCRHomoglyphs.swift
// Vision の英語モデルは短いラテン文字列をキリル文字の同形異字で返すことがある(実測: 入力欄の `ap` を
// `аpар` = U+0430・U+0440 と読んだ。日本語モデルを載せると `ap`)。ラテン文字の期待値と突き合わせる前に
// 同形のキリル・ギリシャ文字をラテン文字へ畳む。**期待値が ASCII のときだけ使う**(ロシア語などの
// 期待値を壊さない)。

import Foundation

public enum OCRHomoglyphs {

    /// 見た目がラテン文字と区別できないものだけ(字形が違う文字は入れない = 別の文字を一致にしない)
    static let latinLookalikes: [Character: Character] = [
        "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x", "і": "i", "ј": "j",
        "ѕ": "s", "һ": "h", "ԁ": "d", "ԛ": "q", "ԝ": "w",
        "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C",
        "Т": "T", "Х": "X", "І": "I", "Ј": "J", "Ѕ": "S",
        "ο": "o", "ν": "v", "Α": "A", "Β": "B", "Ε": "E", "Ζ": "Z", "Η": "H", "Ι": "I", "Κ": "K",
        "Μ": "M", "Ν": "N", "Ο": "O", "Ρ": "P", "Τ": "T", "Υ": "Y", "Χ": "X",
    ]

    public static func foldToLatin(_ text: String) -> String {
        String(text.map { latinLookalikes[$0] ?? $0 })
    }
}
