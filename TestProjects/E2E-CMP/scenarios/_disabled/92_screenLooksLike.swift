// 92_screenLooksLike.swift
// FM(Foundation Models)の画像判定を要するため通常実行(scenarios/ 直下)には載せず _disabled/ に置く。
// **既定スイートに入れてはいけない**: screenLooksLike は FM の非決定的な判定なので、
// 生きた FM で回すとフレーク源になる(FM が死んでいる間は skip されるので緑のまま気付けない)。
// 実行は `Scripts/fm-verify.sh`(90_自己修復 と一緒に一時的に有効化して ios-fm プロファイルで回す)。
//
// fleetest 機能: screenLooksLike(スクリーンショットと自然言語記述の FM 照合)。
// 記述は「文字が読めるか」ではなく**画面の構造**を書く(語句の一致に依存させるとアプリの
// 文言変更で落ちる。FM に渡すのは画像なので、レイアウトの言葉で書くのが安定する)。
//
// **2026-09-03: 入力画面の scene を落とした**。この対照は直近8回中7回赤で、原因を測ったところ
// **文言でも待ち時間でも直らない**ことが分かった:
//   - 同じ画面の説明文を4案(日本語3・英語1)当てても、手元で撮ったスクショでは英語案が 3/3 通り、
//     **M1Max で撮った同じ画面のスクショでは4案とも 0/2**
//   - 同一画像に対しては決定的(greedy)で、**画像を替えると 5/5 → 0/5 で反転する**
//     (どちらも 1206x2622・目には同じ画面。PNG のバイト列だけが違う)
//   - 遷移の待ち(wait 1.5s)を足しても変わらない
// つまり **screenLooksLike の判定は「同じ画面の別の撮り方」で裏返る**ので、
// 厳密な合否ゲートには使えない。**残すのは肯定側1つだけ**(ホーム画面は手元でもランナーでも
// 安定して通る)。判定の安定性そのものを対照にしたくなったら、まず撮り方を固定する手段が要る。

import FTDSL

@TestClass(app: "com.ftester.e2e")
class 画面全体をFMで検証できること {

    @Test("ホーム画面を screenLooksLike が肯定する")
    func S0010() {
        scenario {
            scene(1, "ホーム画面を screenLooksLike で検証") {
                condition {
                    launchApp()
                }.expectation {
                    exist("#txt_home_marker")
                    screenLooksLike("画面上部に見出しがあり、その下に画面遷移用のボタンが縦一列に並んだ一覧。"
                             + "最下部にタブバーがある")
                }
            }
        }
    }
}
